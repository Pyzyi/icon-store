export const LANGUAGES = /** @type {const} */ (['de', 'en']);

/**
 * @param {'de' | 'en'} lang
 * @param {string} key
 * @param {Record<string, string | number>} [params]
 */
export function translate(lang, key, params = {}) {
  const dict = /** @type {Record<string, string>} */ (MESSAGES[lang]);
  const template = dict[key] ?? /** @type {Record<string, string>} */ (MESSAGES.en)[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : `{${name}}`));
}

/** @param {readonly string[]} preferred e.g. navigator.languages */
export function pickLanguage(preferred) {
  for (const p of preferred) {
    const base = p.toLowerCase().split('-')[0];
    if (base === 'de' || base === 'en') return base;
  }
  return 'en';
}
